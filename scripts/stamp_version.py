"""Generate application and Windows EXE version from pipeline number."""
import re
import sys
from pathlib import Path


def make_version(base, run):
    if not re.fullmatch(r"\d+\.\d+", base) or not re.fullmatch(r"[1-9]\d*", run):
        raise ValueError("Expected BASE_VERSION=0.1 and a positive run number")
    major, minor = map(int, base.split("."))
    build = int(run)
    if max(major, minor, build) > 65535:
        raise ValueError("Windows version components must be <= 65535")
    return f"{major}.{minor}.{build}"


def stamp_version(base, run, root):
    version = make_version(base, run)
    major, minor, build = map(int, version.split("."))
    win = (major, minor, build, 0)
    (root / "version.py").write_text(
        f'"""Version generated by GitHub Actions."""\nAPP_VERSION = "{version}"\n',
        encoding="utf-8")
    (root / "windows_version_info.txt").write_text(
        f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers={win!r}, prodvers={win!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
    subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'medneem'),
      StringStruct('FileDescription', 'Videoglue'),
      StringStruct('FileVersion', '{version}.0'),
      StringStruct('InternalName', 'Videoglue'),
      StringStruct('OriginalFilename', 'Videoglue.exe'),
      StringStruct('ProductName', 'Videoglue'),
      StringStruct('ProductVersion', '{version}.0')
    ])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""", encoding="utf-8")
    return version


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("Usage: stamp_version.py BASE_VERSION RUN_NUMBER")
    print(stamp_version(sys.argv[1], sys.argv[2], Path(__file__).resolve().parent.parent))
